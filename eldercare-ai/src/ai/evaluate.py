"""Evaluate the local classifiers on the held-out sets and write docs/AI_EVALUATION.md.

Run:  python -m src.ai.evaluate
"""
from pathlib import Path

from sklearn.metrics import accuracy_score, classification_report, f1_score

from .assistant import URGENCY_EMERGENCY
from .local_responder import has_emergency, has_self_harm
from .classifiers import intent_classifier, urgency_classifier
from . import rag
from .anomaly import detector
from .data.eval_sets import (DOC_EVAL, INTENT_EVAL, INTENT_EVAL_HARD, OUT_OF_KB, RAG_EVAL, REMINDER_EVAL, URGENCY_EVAL,
                             URGENCY_EVAL_FRESH)
from .doc_extract import parse_medications
from .reminder_nlu import parse_reminder


def run():
    out = {}
    for name, clf, data in (("Intent classifier, standard set", intent_classifier(), INTENT_EVAL),
                            ("Intent classifier, hard set (typos, indirect phrasing)", intent_classifier(), INTENT_EVAL_HARD),
                            ("Urgency classifier, development set (used for tuning)", urgency_classifier(), URGENCY_EVAL),
                            ("Urgency classifier, FRESH set (not used for tuning)", urgency_classifier(), URGENCY_EVAL_FRESH)):
        y_true = [l for l, _ in data]
        y_pred = [clf.predict(t)[0] for _, t in data]
        out[name] = {
            "n": len(data), "accuracy": accuracy_score(y_true, y_pred),
            "macro_f1": f1_score(y_true, y_pred, average="macro", zero_division=0),
            "report": classification_report(y_true, y_pred, zero_division=0),
            "errors": [(t, l, p) for (l, t), p in zip(data, y_pred) if l != p],
        }
    out["_hybrid"] = hybrid_emergency()
    out["_rag"] = rag_eval()
    out["_reminder"] = reminder_eval()
    out["_doc"] = doc_eval()
    out["_sensor"] = sensor_eval()
    return out


def rag_eval():
    top1 = top3 = 0
    for q, doc in RAG_EVAL:
        got = [p.doc_id for p in rag.retrieve(q)]
        top1 += bool(got) and got[0] == doc
        top3 += doc in got
    rejected = sum(not rag.retrieve(q) for q in OUT_OF_KB)
    return {"n": len(RAG_EVAL), "hit1": top1 / len(RAG_EVAL), "hit3": top3 / len(RAG_EVAL),
            "ood_n": len(OUT_OF_KB), "ood_rejected": rejected / len(OUT_OF_KB)}


def reminder_eval():
    ok = sum((d := parse_reminder(t)).task == task and d.time == tm and d.problem == prob for t, task, tm, prob in REMINDER_EVAL)
    return {"n": len(REMINDER_EVAL), "accuracy": ok / len(REMINDER_EVAL)}


def doc_eval():
    exp_total = found = cands = correct = 0
    for text, expected in DOC_EVAL:
        got = {(c.name.lower(), c.strength.lower()) for c in parse_medications(text)}
        want = {(n.lower(), s.lower()) for n, s in expected}
        exp_total += len(want); cands += len(got); correct += len(got & want); found += len(got & want)
    return {"expected": exp_total, "extracted": cands, "recall": found / exp_total, "precision": correct / cands if cands else 0.0}


def sensor_eval():
    """Synthetic data only: these numbers say nothing about real people or real devices."""
    from src.safety.sensor_sim import NORMAL, simulate
    from src.services.fall_service import assess
    seeds = range(7000, 7100)
    res = {}
    for sc in NORMAL + ("stumble", "fall_soft", "fall"):
        outs = [assess(simulate(sc, s), 2.5)["outcome"] for s in seeds]
        res[sc] = {k: outs.count(k) / len(outs) for k in ("fall", "unusual", "none")}
    return res


def hybrid_emergency():
    """Emergency detection as the app really does it: keyword rules OR ML urgency >= {URGENCY_EMERGENCY}."""
    clf, res = urgency_classifier(), {}
    for name, data in (("development set", URGENCY_EVAL), ("fresh set", URGENCY_EVAL_FRESH)):
        emerg = [t for l, t in data if l == "emergency"]
        other = [t for l, t in data if l != "emergency"]
        hit = lambda t: has_emergency(t) or has_self_harm(t) or clf.predict(t)[2]["emergency"] >= URGENCY_EMERGENCY
        ml_only = sum(clf.predict(t)[2]["emergency"] >= URGENCY_EMERGENCY for t in emerg)
        res[name] = {"emergency_n": len(emerg), "ml_only_recall": ml_only / len(emerg),
                     "hybrid_recall": sum(hit(t) for t in emerg) / len(emerg),
                     "false_alarms": [t for t in other if hit(t)], "other_n": len(other)}
    return res


def to_markdown(res) -> str:
    lines = ["# AI evaluation (local classifiers)", "",
             "Generated by `python -m src.ai.evaluate`. Test sets are hand-written, small and English only, "
             "and are never used for training, so figures are indicative, not guarantees.", "",
             "## Development notes",
             "- First run (before any tuning): urgency accuracy 0.85, **emergency recall 0.70**. The model missed "
             "\"i am going to faint\", \"i have taken too many pills\" and \"i passed out in the kitchen\".",
             "- Response: added training phrasings for those families, and added a deterministic keyword safety net "
             "that runs alongside the model (either one triggers the emergency message). The original urgency set is "
             "therefore a *development* set; the FRESH set was written afterwards and is the fairer estimate.",
             "- A false alarm (showing the emergency message unnecessarily) is accepted over a missed emergency.", ""]
    h = res.pop("_hybrid")
    rg, rm, dc, sn = res.pop("_rag"), res.pop("_reminder"), res.pop("_doc"), res.pop("_sensor")
    for name, r in res.items():
        lines += [f"## {name}", f"- Test utterances: {r['n']}", f"- Accuracy: {r['accuracy']:.2f}",
                  f"- Macro F1: {r['macro_f1']:.2f}", "", "```", r["report"].rstrip(), "```", ""]
        if r["errors"]:
            lines.append("Misclassified:")
            lines += [f"- \"{t}\": expected {l}, predicted {p}" for t, l, p in r["errors"]]
            lines.append("")
    lines += [f"## Emergency detection as deployed (keyword rules OR ML probability >= {URGENCY_EMERGENCY})",
              "The keyword rules were extended after the first run using general emergency vocabulary, so the "
              "hybrid result on the fresh set is not a pure held-out measurement.", ""]
    for name, r in h.items():
        lines.append(f"- {name}: ML-only recall {r['ml_only_recall']:.2f}, hybrid recall {r['hybrid_recall']:.2f} "
                     f"({r['emergency_n']} emergency phrases); false alarms on {r['other_n']} non-emergency phrases: "
                     f"{len(r['false_alarms'])}" + (f" ({'; '.join(r['false_alarms'])})" if r["false_alarms"] else ""))
    lines += ["", "## Knowledge-base retrieval (TF-IDF)",
              f"- {rg['n']} questions: top-1 correct source {rg['hit1']:.2f}, correct source in top 3 {rg['hit3']:.2f}",
              f"- {rg['ood_n']} off-topic questions correctly answered with \"no information\": {rg['ood_rejected']:.2f}", "",
              "## Reminder understanding (rules)", f"- {rm['n']} requests, exact task, time and problem match: {rm['accuracy']:.2f}", "",
              "## Prescription extraction (rules on clean text; OCR adds its own errors)",
              f"- {dc['expected']} expected medicines: recall {dc['recall']:.2f}, precision {dc['precision']:.2f} "
              f"({dc['extracted']} extracted). The samples include a deliberately hard line (\"Vit D3\") to show limits.", "",
              "## Sensor anomaly detection and fall rule (SYNTHETIC data, 100 unseen windows per activity, threshold 2.5 g)",
              "These figures come from simulated signals made by this project. They are NOT real-world accuracy.", ""]
    lines += [f"- {sc}: fall {v['fall']:.2f}, unusual {v['unusual']:.2f}, none {v['none']:.2f}" for sc, v in sn.items()]
    return "\n".join(lines)


if __name__ == "__main__":
    res = run()
    md = to_markdown(res)
    Path(__file__).resolve().parents[2].joinpath("docs", "AI_EVALUATION.md").write_text(md, encoding="utf-8")
    print(md)
